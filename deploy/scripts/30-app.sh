# ------------------------------------------------------------------ existing
# A previous Medusa project may exist in ~/sparky-commerce. Inventory it and
# back it up. Nothing is modified or deleted.
stage_existing() {
  local found=0 d
  for d in /root/sparky-commerce /home/*/sparky-commerce; do
    [ -d "$d" ] || continue
    found=1
    info "existing project found: $d"
    local be="$d/apps/backend" ts out ver
    ts=$(date -u +%Y%m%dT%H%M%SZ)
    out="$SPARKY_BACKUP_DIR/pre-install-existing-$ts"
    install -d -m 0700 "$out"
    if [ -f "$be/package.json" ]; then
      ver=$(jq -r '.dependencies["@medusajs/medusa"] // "unknown"' "$be/package.json")
      info "  @medusajs/medusa: $ver   package manager lockfiles: $(cd "$be" && ls package-lock.json yarn.lock pnpm-lock.yaml 2>/dev/null | tr '\n' ' ')"
      echo "medusa=$ver" >"$out/inventory.txt"
    fi
    # code snapshot (without node_modules/build output); includes .env → 0600 root
    run tar --exclude=node_modules --exclude=.medusa --exclude=.next -czf "$out/project.tgz" -C "$(dirname "$d")" "$(basename "$d")"
    chmod 600 "$out/project.tgz"
    local envf url
    for envf in "$be/.env" "$d/.env"; do
      [ -f "$envf" ] || continue
      url=$(grep -E '^DATABASE_URL=' "$envf" | tail -1 | cut -d= -f2- | tr -d '"'"'" || true)
      if [ -n "$url" ]; then
        CURRENT_CMD="pg_dump existing database (url redacted)"
        if pg_dump --format=custom --no-owner --file="$out/existing-db.dump" "$url" >>"$SPARKY_LOG" 2>&1; then
          chmod 600 "$out/existing-db.dump"
          pass "  existing database dumped to $out/existing-db.dump"
        else
          warn "  could not dump the existing database (see log); continuing without modifying it"
        fi
      fi
    done
    # processes that would collide with our ports
    local p pid cmd
    for p in 3000 9000; do
      pid=$(lsof -t -iTCP:"$p" -sTCP:LISTEN 2>/dev/null | head -1 || true)
      [ -n "$pid" ] || continue
      cmd=$(tr '\0' ' ' </proc/"$pid"/cmdline | cut -c1-100)
      case "$cmd" in *"$SPARKY_HOME"*) continue ;; esac
      if [ "${EXISTING_STOP:-no}" = yes ]; then
        warn "  stopping process on port $p ($cmd) as requested (EXISTING_STOP=yes)"
        if have pm2; then pm2 stop all >>"$SPARKY_LOG" 2>&1 || true; fi
        kill "$pid" || true
      else
        die "port $p is used by the existing installation ($cmd). Stop it yourself or re-run with EXISTING_STOP=yes (a backup is in $out)."
      fi
    done
    pass "  existing installation backed up to $out (left untouched)"
  done
  [ "$found" = 1 ] || skip "no existing ~/sparky-commerce installation"
}

# -------------------------------------------------------------------- medusa
new_release() {
  local sha id
  sha=$(git -C "$REPO_DIR" rev-parse --short HEAD 2>/dev/null || echo nogit)
  local pending
  pending=$(cat "$SPARKY_STATE_DIR/pending-release" 2>/dev/null || true)
  if [ -n "$pending" ] && [ -d "$pending" ] && [[ "$pending" == *"-$sha" ]]; then
    RELEASE_DIR=$pending # resume an interrupted build of the same commit
  else
    id="$(date -u +%Y%m%d%H%M%S)-$sha"
    RELEASE_DIR="$SPARKY_RELEASES/$id"
  fi
  CURRENT_CMD="copy source to $RELEASE_DIR"
  install -d -o "$SPARKY_USER" -g "$SPARKY_USER" "$RELEASE_DIR"
  rsync -a --delete \
    --exclude node_modules --exclude .medusa --exclude .next --exclude '.env' --exclude '.env.*' \
    --exclude 'apps/backend/static' --exclude 'apps/backend/private-uploads' --exclude 'test-results' --exclude 'playwright-report' \
    --include '.env.example' \
    "$REPO_DIR/" "$RELEASE_DIR/"
  chown -R "$SPARKY_USER:$SPARKY_USER" "$RELEASE_DIR"
  echo "$RELEASE_DIR" >"$SPARKY_STATE_DIR/pending-release"
  export RELEASE_DIR
}

